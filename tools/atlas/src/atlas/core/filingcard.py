"""Generated filing cards: a section's staff-facing README.md (ADR 0025).

A section marked ``"filingCard": true`` in the map gets ``<section>/README.md``
with an "I have... / it goes in" table built from its children's
``description`` lines. The table sits between markers, so conform refreshes it
when the map changes and leaves every line outside the markers alone - the same
contract as the Atlas block in AGENTS.md. The card can never disagree with the
map because the map is all it is made from.

Staff-facing copy: plain words, no em dashes.
"""

from __future__ import annotations

from .mapfile import DriveMap, Section
from .projectmd import dossier_lines

CARD_BEGIN = "<!-- atlas:card-begin -->"
CARD_END = "<!-- atlas:card-end -->"
CARD_FILE = "README.md"


class CardBlockError(Exception):
    """The card markers in a README are broken; a person has to fix them."""


def card_sections(m: DriveMap) -> tuple[Section, ...]:
    return tuple(s for s in m.sections if s.filing_card)


def card_path(section: Section) -> str:
    return f"{section.id}/{CARD_FILE}"


def card_paths(m: DriveMap) -> tuple[str, ...]:
    return tuple(card_path(s) for s in card_sections(m))


def card_block_lines(section: Section) -> list[str]:
    rows = [f"| {text.replace('|', chr(92) + '|')} | `{child}` |"
            for child, text in section.descriptions]
    return [
        CARD_BEGIN,
        "<!-- Generated by Atlas from the drive map. Conform rewrites this block; keep notes outside it. -->",
        "",
        "## Where does it go?",
        "",
        "Find what you have, then file it in that folder. If a folder is missing, add it with Atlas",
        "(`_tools\\Atlas.bat`, select the project, press `a`). Never make folders here by hand.",
        "",
        "| I have... | It goes in |",
        "|-----------|------------|",
        *rows,
        CARD_END,
    ]


def card_lines(section: Section) -> list[str]:
    """A new card: a title, then the generated block."""
    return [f"# {section.id}", "", *card_block_lines(section)]


def _span(lines: list[str]) -> tuple[int, int] | None:
    marks = [line.strip() for line in lines]
    begins = [i for i, mark in enumerate(marks) if mark == CARD_BEGIN]
    ends = [i for i, mark in enumerate(marks) if mark == CARD_END]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise CardBlockError("Atlas card markers in README.md are broken; fix them by hand")
    return begins[0], ends[0]


def card_current(text: str, section: Section) -> bool:
    # Split as the writer splits (#61): U+2028 and friends are text, not breaks.
    lines = dossier_lines(text)
    try:
        span = _span(lines)
    except CardBlockError:
        return False
    if span is None:
        return False
    start, end = span
    return [line.rstrip() for line in lines[start:end + 1]] == card_block_lines(section)


def with_card_block(lines: list[str], section: Section) -> list[str]:
    """``lines`` with the card block refreshed in place, or inserted after the
    first heading (else at the top). Raises CardBlockError on broken markers."""
    block = card_block_lines(section)
    span = _span(lines)
    if span is not None:
        start, end = span
        return lines[:start] + block + lines[end + 1:]
    first = next((i for i, line in enumerate(lines) if line.strip()), None)
    if first is not None and lines[first].startswith("# "):
        head, rest = lines[:first + 1], lines[first + 1:]
    else:
        head, rest = [], list(lines)
    while rest and not rest[0].strip():
        rest = rest[1:]
    out = head + ([""] if head else []) + block
    return out + ([""] + rest if rest else [])
