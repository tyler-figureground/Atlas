"""The human-facing Reference Sets gallery: one self-contained HTML page.

``atlas refs gallery`` reads the same card front matter and folder layout as
``refs index`` and writes ``Reference Sets.html`` beside the sets README - a
browse page for people, where the README answers agents and the Mermaid map
serves the VS Code reader. One tile per set, grouped by the same lifecycle
bands (``BANDS`` in ``refsets.py``), with a live filter and a sticky band nav.

Self-contained by contract: inline CSS, a few lines of vanilla JS, every href
relative and URL-encoded, no network, no external fonts or libraries - the
page must work from ``file://`` on the library drive. Deterministic: no
timestamps anywhere, so regenerating over unchanged cards is byte-identical.
The page is a pure generated artifact - edit the cards, never the page.
"""

