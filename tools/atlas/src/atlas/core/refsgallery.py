_USE_WHEN_STRIP = re.compile(r"^>?\s*\*\*Use when:\*\*\s*(.+)$")
_USE_WHEN_BULLET = re.compile(r"^[-*]\s*\*\*Use:\*\*\s*(.+)$")
_PREFIX = re.compile(r"^(\d+)\s*")


def when_to_use(card_text: str, fallback: str) -> str:
    """The card's first "when to use" line: the Phase 3 top strip
    (``> **Use when:**``), else the first ``- **Use:**`` bullet, else the
    card title. Trailing markdown stop kept out; one line only."""
    for line in card_text.splitlines():
        match = _USE_WHEN_STRIP.match(line.strip()) or _USE_WHEN_BULLET.match(line.strip())
        if match:
            return match.group(1).strip().rstrip(".")
    return fallback


def split_name(folder_name: str) -> tuple[str, str]:
    """(number, name) from a set folder: "03 Code Analysis" -> ("03", "Code
    Analysis"). No numeric prefix: the number is empty and the name is whole."""
    match = _PREFIX.match(folder_name)
    if match:
        return match.group(1), folder_name[match.end():].strip()
    return "", folder_name


def _href(*parts: str) -> str:
    """A relative, URL-encoded href from path parts. Forward slashes always -
    browsers resolve them from ``file://`` fine."""
    return quote("/".join(parts))


def exemplar_href(set_name: str, exemplar_folder: Path) -> str:
    """The exemplar's quick link: a frozen PDF opens in the browser directly,
    so link to the file itself; anything else links to the folder."""
    pdfs = sorted(p for p in exemplar_folder.iterdir() if p.suffix.lower() == ".pdf")
    if pdfs:
        return _href(set_name, exemplar_folder.name, pdfs[0].name)
    return _href(set_name, exemplar_folder.name) + "/"


def thumbnail(set_name: str, refset: RefSet) -> str | None:
    """The tile's thumbnail: the first PNG under the first exemplar that has a
    ``Pages`` folder of them (the drawing sets' page exports). Iterdir, never
    rglob - the drive walk rules. None means a plain tile."""
    for exemplar in refset.exemplars:
        pages = exemplar.folder / "Pages"
        if not pages.is_dir():
            continue
        pngs = sorted(p for p in pages.iterdir() if p.suffix.lower() == ".png")
        if pngs:
            return _href(set_name, exemplar.folder.name, "Pages", pngs[0].name)
    return None


