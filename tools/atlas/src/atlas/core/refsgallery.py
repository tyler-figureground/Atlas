def _tile(refset: RefSet) -> str:
    set_name = refset.folder.name
    number, name = split_name(set_name)
    status = refset.status if refset.status in STATUS_CLASSDEFS else "unknown"
    status_word = refset.status or "no status"
    card_text = (refset.folder / CARD).read_text(encoding="utf-8", errors="replace")
    when = when_to_use(card_text, refset.title or name)
    search = html.escape(" ".join([set_name, refset.type, status_word, when]).lower(),
                       quote=True)
    parts = ['<article class="tile" data-search="%s">' % search]
    shot = thumbnail(set_name, refset)
    if shot:
        parts.append(f'<img src="{shot}" alt="{html.escape(name)} exemplar page" '
                     'loading="lazy">')
    chip = f'<span class="chip">{html.escape(number)}</span>' if number else ""
    parts.append(f'<h3>{html.escape(name)} {chip}'
                 f'<span class="badge {status}">{html.escape(status_word)}</span></h3>')
    parts.append(f'<p class="when">{html.escape(when)}</p>')
    card = _href(set_name, CARD)
    folder = _href(set_name) + "/"
    exemplars = " ".join(
        f'<a href="{exemplar_href(set_name, ex.folder)}">{html.escape(ex.id)}</a>'
        for ex in refset.exemplars)
    parts.append(f'<p class="links"><a href="{card}">Card</a>'
                 f'<a href="{folder}">Folder</a>'
                 f'<span class="ex">{exemplars}</span></p>')
    parts.append("</article>")
    return "\n".join(parts)


def gallery_html(root: Path, sets: list[RefSet]) -> str:
    """The whole page, deterministic: same cards and folders, same bytes."""
    banded = _banded(sets)
    nav = "".join(f'<a href="#{band_id.lower()}">{html.escape(name)}</a>'
                  for name, band_id, _ in banded)
    sections = []
    for name, band_id, band_sets in banded:
        tiles = "\n".join(_tile(refset) for refset in band_sets)
        sections.append(f'<section class="band" id="{band_id.lower()}">\n'
                        f"<h2>{html.escape(name)}</h2>\n"
                        f'<div class="grid">\n{tiles}\n</div>\n</section>')
    return f"""<!DOCTYPE html>
<!-- {FOOTER} -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Reference Sets</title>
<style>{_CSS}</style>
</head>
<body>
<header>
<h1>Reference Sets</h1>
<p class="lede">{html.escape(LEDE)}</p>
<p class="junior">New here? Start with the
<a href="{_href(JUNIOR_GUIDE)}">Junior Quick Start</a>.</p>
<input id="filter" type="search" placeholder="Filter sets&hellip;" aria-label="Filter sets">
</header>
<nav class="bands">{nav}</nav>
<main>
{chr(10).join(sections)}
</main>
<footer>{html.escape(FOOTER)}</footer>
<script>{_JS}</script>
</body>
</html>
"""


def write_gallery(root: Path, sets: list[RefSet]) -> Path:
    """Write ``Reference Sets.html`` beside the sets README. Pure generated
    artifact - written directly, like ``atlas tyler --write``."""
    path = root / GALLERY_NAME
    path.write_bytes(gallery_html(root, sets).encode("utf-8"))
    return path


